    function under(p) { return typeof p === 'string' && (p === HOME || p.indexOf(HOME + '/') === 0); }
    function wrap(name, test) {
      var f = FS[name];
      FS[name] = function () { var r = f.apply(this, arguments); if (test.apply(null, arguments)) soon(); return r; };
    }
    wrap('close', function (stream) { return (stream.flags & 3) !== 0 && under(stream.path); });
    wrap('rename', function (a, b) { return under(a) || under(b); });
    wrap('unlink', under);
    wrap('rmdir', under);
    wrap('utime', under);
    wrap('truncate', under);
